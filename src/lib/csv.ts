/**
 * One CSV cell. Values are quoted when needed, and text that a spreadsheet would run as a formula (starting with
 * = + - @ or a tab/return) gets a leading apostrophe so an opened file can never execute anything.
 */
export function csvCell(value: unknown): string {
  let s = value === null || value === undefined ? "" : String(value);
  if (/^[=+\-@\t\r]/.test(s) && !/^[+-]?[\d\s().-]+$/.test(s)) s = `'${s}`;
  return /[",\r\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** A whole CSV file with a header row and a byte-order mark, so Excel reads accents and Hindi names correctly. */
export function toCsv(headers: string[], rows: unknown[][]): string {
  return "﻿" + [headers, ...rows].map((r) => r.map(csvCell).join(",")).join("\r\n") + "\r\n";
}
